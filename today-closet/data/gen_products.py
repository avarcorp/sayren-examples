def variants(colors, sizes, stock):
    out=[]; n=0
    for c in colors:
        for s in (sizes or [None]):
            q = stock[n % len(stock)]; n+=1
            out.append({"valueNames":[c,s] if s else [c],"stockQuantity":q})
    return out

